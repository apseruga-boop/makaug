function siteLang(value) {
  const code = String(value || 'en').trim().toLowerCase().replace(/[^a-z]/g, '').slice(0, 8);
  return SITE_LANGS.includes(code) ? code : 'en';
}

function bookingSay(lang, english, params) {
  const code = siteLang(lang);
  const template = (code !== 'en' && PHRASES[code] && PHRASES[code][english]) || english;
  if (!params) return template;
  return String(template).replace(/\{(\w+)\}/g, (_all, key) => (params[key] == null ? '' : String(params[key])));
}

function replyWindow(lang, hours) {
  const count = Number(hours);
  if (count === 1) return bookingSay(lang, '1 hour');
  return bookingSay(lang, '{n} hours', { n: Number.isFinite(count) ? count : hours });
}

