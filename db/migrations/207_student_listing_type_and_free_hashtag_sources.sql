-- 207_student_listing_type_and_free_hashtag_sources.sql
-- Students category spelling, and free public hashtag sources.
--
-- 1. properties.listing_type 'students' is stored as 'student' so imported
--    hostels sit in the same moderation queue and public student section as
--    the rest of the student inventory. Old values are copied to
--    listing_type_student_alias_207_backup first.
-- 2. Free public hashtag sources (no phone, no paid API, 62-day lookback)
--    are inserted into property_source_registry. Any row that already used
--    one of these source keys is copied to free_hashtag_sources_207_backup.
--
-- Does not touch WhatsApp tables. Does not send messages.
-- Rollback: scripts/rollback-207-student-alias-and-free-hashtags.sql
-- (that file is outside db/migrations, so it does not run on deploy).

SET LOCAL lock_timeout = '8s';
SET LOCAL statement_timeout = '180s';
SET LOCAL TIME ZONE 'UTC';

CREATE TABLE IF NOT EXISTS listing_type_student_alias_207_backup (
  property_id UUID PRIMARY KEY,
  listing_type TEXT NOT NULL,
  extra_fields JSONB,
  updated_at TIMESTAMPTZ,
  backed_up_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO listing_type_student_alias_207_backup (property_id, listing_type, extra_fields, updated_at)
SELECT id, listing_type, extra_fields, updated_at
FROM properties
WHERE LOWER(TRIM(COALESCE(listing_type, ''))) = 'students'
ON CONFLICT (property_id) DO NOTHING;

UPDATE properties p
SET listing_type = 'student',
    extra_fields = COALESCE(p.extra_fields, '{}'::jsonb) || jsonb_build_object(
      'listing_type_normalized_at', NOW()::text,
      'listing_type_normalized_by', 'student-alias-207-20261110',
      'listing_type_previous_value', p.listing_type
    ),
    updated_at = NOW()
FROM listing_type_student_alias_207_backup b
WHERE p.id = b.property_id
  AND LOWER(TRIM(COALESCE(p.listing_type, ''))) = 'students';

